// Diseñar e implementar una clase CuentaBancaria que aplique encapsulamiento
// (atributos privados titular y saldo), constructor para inicializar valores, y
// métodos públicos depositar, retirar (validando fondos suficientes) y consultarSaldo.

public class CuentaBancaria {

    private String titular;
    private double saldo;

    public CuentaBancaria(String titular, double saldoInicial) {
        this.titular = titular;
        this.saldo = saldoInicial;
    }

    public String getTitular() {
        return titular;
    }

    public void depositar(double monto) {
        if (monto > 0) {
            saldo += monto;
        }
    }

    public boolean retirar(double monto) {
        if (monto > 0 && monto <= saldo) {
            saldo -= monto;
            return true;
        }
        return false;
    }

    public double consultarSaldo() {
        return saldo;
    }
}
